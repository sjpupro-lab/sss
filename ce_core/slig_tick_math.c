/* ────────────────────────────────────────────────────────────────
 *  Frequency-space search / distance primitives (v3 §5)
 * ──────────────────────────────────────────────────────────────── */

uint64_t tick_distance_precise(const CEUnit *a, const CEUnit *b) {
    if (!a || !b) return 0;
    const uint8_t *pa = ce_cbytes(a);
    const uint8_t *pb = ce_cbytes(b);
    uint64_t dist = 0;
    /* 8 CETiers × { minus[4], plus[4] } = 16 packed-uint32 windows. */
    for (int t = 0; t < 16; t++) {
        uint32_t va = tick_read(&pa[t * 4]);
        uint32_t vb = tick_read(&pb[t * 4]);
        int64_t diff = (int64_t)va - (int64_t)vb;
        dist += (diff < 0) ? (uint64_t)(-diff) : (uint64_t)diff;
    }
    return dist;
}

uint32_t tick_cosine_similarity(const CEUnit *a, const CEUnit *b) {
    if (!a || !b) return 0;
    const uint8_t *pa = ce_cbytes(a);
    const uint8_t *pb = ce_cbytes(b);
    uint64_t dot = 0, norm_a = 0, norm_b = 0;
    for (int i = 0; i < 64; i++) {
        dot    += (uint64_t)pa[i] * (uint64_t)pb[i];
        norm_a += (uint64_t)pa[i] * (uint64_t)pa[i];
        norm_b += (uint64_t)pb[i] * (uint64_t)pb[i];
    }
    /* For a 64-byte all-FF cell norm = 64 × 65025 ≈ 4.16M < 2^22. */
    uint32_t na = tick_sqrt((uint32_t)norm_a);
    uint32_t nb = tick_sqrt((uint32_t)norm_b);
    if (na == 0 || nb == 0) return 0;
    /* Scale to ~[0, 256]: dot × 256 / (na × nb). */
    uint64_t scaled = (uint64_t)dot * 256u;
    uint64_t denom  = (uint64_t)na * (uint64_t)nb;
    if (denom == 0) return 0;
    return (uint32_t)(scaled / denom);
}

uint32_t tick_frequency_distance(const CEUnit *a, const CEUnit *b) {
    if (!a || !b) return 0;
    /* inc.G = u DCT [0..7], inc.B = v DCT [0..7] — 16 bytes total per
     * cell. Plain SAD over those captures spectral distance, ignoring
     * metadata (inc.R), energy (inc.A), trigger / audio (dec.*). */
    uint32_t dist = 0;
    const uint8_t *ag = (const uint8_t *)&a->inc.G;
    const uint8_t *bg = (const uint8_t *)&b->inc.G;
    const uint8_t *ab_ = (const uint8_t *)&a->inc.B;
    const uint8_t *bb_ = (const uint8_t *)&b->inc.B;
    for (int i = 0; i < 8; i++) {
        int da = (int)ag[i]  - (int)bg[i];   if (da < 0) da = -da; dist += (uint32_t)da;
        int db = (int)ab_[i] - (int)bb_[i];  if (db < 0) db = -db; dist += (uint32_t)db;
    }
    return dist;
}

